function shuffle(a) {
  for (var i = a.length - 1; i > 0; i--) {
    var j = Math.floor(Math.random() * (i + 1)),
      t = a[i];
    a[i] = a[j];
    a[j] = t;
  }
  return a;
}
function pool(bab) {
  var babs = bab === "all" ? ["1", "2", "3"] : [bab],
    out = [],
    seen = {};
  babs.forEach(function (b) {
    D[b].forEach(function (g) {
      g[1].forEach(function (r) {
        if (r[2].length <= 38 && !seen[r[2]] && !seen[r[0]]) {
          seen[r[2]] = seen[r[0]] = 1;
          out.push(r);
        }
      });
    });
  });
  return out;
}
function startQuiz() {
  var qs;
  if (K.type === "pola") {
    qs = shuffle(
      PQ.filter(function (x) {
        return K.bab === "all" || x[0] === K.bab;
      }),
    )
      .slice(0, 10)
      .map(function (x) {
        return {
          ask: x[1],
          sub: x[2],
          ans: x[3],
          opts: shuffle(x[4].slice()),
          ro: "",
        };
      });
  } else {
    var p = pool(K.bab),
      fwd = K.type === "jp-id";
    qs = shuffle(p.slice())
      .slice(0, 10)
      .map(function (r) {
        var ans = fwd ? r[2] : r[0],
          d = shuffle(p.slice())
            .filter(function (z) {
              return z !== r && (fwd ? z[2] : z[0]) !== ans;
            })
            .slice(0, 3)
            .map(function (z) {
              return fwd ? z[2] : z[0];
            });
        return {
          ask: fwd ? r[0] : r[2],
          sub: fwd ? r[1] : "",
          ans: ans,
          opts: shuffle([ans].concat(d)),
          ro: fwd ? "" : r[1],
        };
      });
  }
  K.qs = qs;
  K.i = 0;
  K.score = 0;
  K.wrong = [];
  K.sel = -1;
  K.mode = "play";
}
